function buildHealthRoute(id,role) {
  if (painScenes[id]) return buildPainRoute(id,role);
  const scene=strokeScenes[id], part=scene[role];
  const self=role==='self', speech=id==='speech';
  const helper=speech?'Вера':'Тимур';
  const witnessCaller=speech?'Саша':'Вера';
  const signal='pressure-0', better='wait-0';
  const cues={
    [signal]:[part.fact,scene.clue],
    [better]:[part.improvement,'Даже если симптомы прошли или ослабли, вызов скорой по-прежнему нужен немедленно.']
  };
  const emergency='В России сразу звонят 103 или 112. Опиши диспетчеру внезапные изменения, назови адрес и время начала. Если точное время неизвестно, скажи, когда человек в последний раз был в обычном состоянии.';
  const story={
    start:{mode:'yellow',lines:scene.opening,question:'Что произойдёт дальше?',links:[['pressure','Продолжить'],['calm','Спокойный дубль']]},
    calm:{parent:'start',continuation:true,mode:'yellow',lines:scene.quiet,question:'Что сейчас происходит?',links:[['calm-end',speech?'В кадр попало пол-лица. Переснимем фото.':'Буквы были на разных листах. Посмотрю на исправленную афишу.']]},
    'calm-end':{parent:'calm',mode:'yellow',lines:[['Ремарка',scene.calmEnd]],outcome:['positive',speech?'Командное фото готово':'Осталась одна афиша'],note:'В этой версии истории никто не почувствовал внезапного изменения самочувствия.'},
    pressure:{parent:'start',continuation:true,mode:'yellow',lines:part.signs,question:self?'Ты замечаешь резкую перемену. Что сделаешь?':'Что в этой сцене требует твоего внимания?',links:[['call',part.call],['delegate',part.delegate],['wait','Может, это усталость. Посмотрю, пройдёт ли само.']]},
    wait:{parent:'pressure',mode:'yellow',lines:[['Ремарка',part.improvement],['Ремарка','При таких внезапных признаках скорую вызывают сразу, даже если стало легче. В России — 103 или 112.']],question:'Что сделаешь теперь?',links:[['call-now','Позвоню 112 сейчас. Расскажу и о том, как всё началось, и о том, что изменилось.']]}
  };
  const decisions={wait:{signals:[signal],miss:true,effect:scene.clue+' Ожидание отложило вызов.',repair:'call-now',recovery:'После этого скорую всё-таки вызвали.'}};
  for (const key of ['call','delegate','call-now']) {
    const parent=key==='call-now'?'wait':'pressure';
    const speaker=key==='delegate'?(self?helper:witnessCaller):(self && speech?helper:'Ты');
    const relay=speaker!=='Ты' && self && !speech?'У учительницы внезапно задвоились буквы и нарушилось равновесие. Мы в школьном вестибюле.':part.relay;
    const explanation=key==='delegate'?'Рядом с тобой набрали 112.':'Вызов 112 принят.';
    story[key]={parent,mode:'red',lines:[['Ремарка',explanation],[speaker,relay,'Разговор с диспетчером 112'],['Ремарка','Диспетчеру называют город, улицу, номер дома и вход в школу.'],['Диспетчер','Записал адрес школы и куда подойти. Когда это началось?']],question:'Что передашь о времени?',links:[[key+'-time','Скажу, когда всё было как обычно и когда заметили перемену.']]};
    if(key==='call-now') story[key].lines.splice(2,0,[speaker,'Сейчас стало лучше. Расскажу, какие признаки были вначале.']);
    const last=story[key].lines.length-1;
    const cue=key+'-'+last;
    cues[cue]=['Когда это началось','Диспетчеру важно знать время начала или когда человек в последний раз был в обычном состоянии.'];
    decisions[key]={signals:[key==='call-now'?better:signal],effect:explanation+' '+scene.clue};
    const timeReport = speech ? scene.timing : self && speaker==='Ты'
      ? 'В 12:25 я ещё видела одну афишу. Сразу после этого буквы раздвоились, и я пошатнулась.'
      : 'В 12:25 мы вешали афишу. Сразу после этого Марина Сергеевна пошатнулась и взялась за спинку скамьи.';
    story[key+'-time']={parent:key,mode:'red',lines:[[speaker,timeReport],['Диспетчер','Бригада направлена. Оставайтесь на связи, я скажу, что делать до её приезда.']],outcome:['positive','Скорую вызвали, время передали'],note:scene.clue+' '+emergency};
    decisions[key+'-time']={signals:[cue],effect:'Диспетчер получил время, которое участники действительно помнят.'};
  }
  return {story,cues,decisions};
}

