function buildPainRoute(id, role) {
  const scene = painScenes[id];
  const actions = scene[role];
  const caller = role === 'self' ? scene.caller : 'Ты';
  const story = {
    start: {mode:'yellow', lines:scene.opening, links:[['pressure','Продолжить'],['calm','Спокойный дубль']]},
    calm: {parent:'start', continuation:true, mode:'yellow', lines:scene.calm, question:'Что дальше?', links:[['calm-end',scene.calmChoice]]},
    'calm-end': {parent:'calm', mode:'yellow', lines:[['Ремарка',scene.calmEnd]], outcome:['positive','Успели вместе'], note:'В этом дубле оба хорошо себя чувствуют.'},
    pressure: {parent:'start', continuation:true, mode:'yellow', lines:scene.signs, question:'Что ты сделаешь сейчас?', links:[['call',actions.call],['wait',actions.wait]]},
    wait: {parent:'pressure', mode:'yellow', lines:[['Ремарка',scene.reason],['Ремарка',scene.clue+' В России можно позвонить 103 или 112.']], question:'Что сделаешь теперь?', links:[['call-now',actions.call]]}
  };
  const cues = {
    'pressure-0':[scene.signal,scene.clue],
    'pressure-2':[scene.dismissal,scene.reason],
    'wait-0':[scene.reason,scene.clue]
  };
  const decisions = {
    wait:{signals:['pressure-0','pressure-2'], miss:true, effect:'Вызов отложили, хотя признаки уже были видны.', repair:'call-now', recovery:'Затем ты организовал вызов скорой.'}
  };
  for (const key of ['call','call-now']) {
    const parent = key === 'call' ? 'pressure' : 'wait';
    story[key] = {parent, mode:'red', lines:[
      ['Ремарка',scene.caller+' набирает 103 и называет город, улицу и номер школы.'],
      [caller,'Мы '+scene.location+'.'],['Диспетчер','Что случилось?']
    ], question:'Что скажешь диспетчеру?', links:[[key+'-report',actions.dispatch]]};
    cues[key+'-2'] = ['Что случилось','Диспетчеру нужны признаки, которые можно описать своими словами.'];
    decisions[key] = {signals:[key === 'call' ? 'pressure-0' : 'wait-0'], effect:'Диспетчер принял звонок и узнал, куда ехать.'};
    story[key+'-report'] = {parent:key, mode:'red', lines:[
      [caller,actions.dispatch],['Диспетчер','Бригада направлена. Оставайтесь на линии.'],['Ремарка',scene.untilHelp]
    ], outcome:['positive','Скорую вызвали'], note:scene.clue+' В России звонят 103 или 112. Оставайся рядом и следуй указаниям диспетчера.'};
    decisions[key+'-report'] = {signals:[key+'-2'], effect:'Диспетчер услышал, что изменилось и когда это началось.'};
  }
  return {story,cues,decisions};
}
