function attentionAtLine(node,index) {
  return node.reaction && index >= node.reaction.index && index < node.reaction.until ? 'black' : node.mode;
}

function loadAttentionScene(pages, route, title) {
  pages.clear();
  for (const [id, data] of Object.entries(route.story)) {
    pages.set(id, {...data, title, lines:data.lines.map(bubbleFromPair),
      links:(data.links || []).map(([id,label])=>({id,label})),
      outcome:data.outcome && {kind:data.outcome[0],headline:data.outcome[1]}});
  }
}

function setAttentionMode(mode) {
  const {name,meaning,chrome} = attentionModes[mode];
  document.documentElement.dataset.code = mode;
  document.querySelector('#mode-name .level-name').textContent = name;
  document.querySelector('#mode-name .level-meaning').textContent = ' · '+meaning;
  document.querySelector('meta[name="theme-color"]').content = chrome;
}

