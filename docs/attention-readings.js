function addReadingChoices(id, role, route) {
  const {story,cues,decisions} = route;
  const item = readingScenes[id];
  const self = role === 'self';
  const byRole = value => value[role] || value;
  const pilot = id === 'money' && !self;
  const sourceDecision = decisions[pilot ? 'check' : 'pressure-act-0'];
  if (!pilot) {
    const [first,second,other] = pressureReadings[id][role];
    const labels = {'pressure-act-0':first,'pressure-act-1':second,alternative:other};
    story.pressure.links = story.pressure.links.map(([key,label])=>[key,labels[key] || label]);
  }
  const levels = (self && item.selfModes) || item.modes || ['yellow','orange'];
  const labels = [(self && item.selfOrdinary) || item.ordinary,(self && item.selfAlert) || item.alert];
  const lines = byRole(item.lines);
  const fact = byRole(item.fact);
  const index = lines.findIndex(line => line[1].includes(fact));
  if (index < 0) throw new Error('Missing attention cue: '+id+'/'+role);
  const endingNote = item.why;
  for (const [i,key] of ['observe','focus'].entries()) {
    story.pressure.links.push([key,labels[i]]);
    const cue = key+'-'+index;
    cues[cue] = [fact,item.why];
    decisions[key] = {signals:sourceDecision.signals,effect:item.why};
    story[key] = {parent:'pressure',mode:levels[i],lines,question:'Что изменилось для тебя сейчас?',links:[]};
    for (const [suffix,mode,label] of [['ease','yellow',item.ease],['watch','orange',(self && item.selfWatch) || item.watch]]) {
      const target = key+'-'+suffix;
      story[key].links.push([target,label]);
      story[target] = {parent:key,mode,lines:item.ending,outcome:[item.outcome || 'positive',item.result],note:endingNote};
      decisions[target] = {signals:[cue],effect:mode === 'yellow' ? item.why : label};
    }
  }
  // The quiet take also allows two different readings of the same next event.
  const original = id === 'project' ? 'calm-act-0' : 'calm-end';
  const quietLabel = id === 'project' ? (self ? 'Проверю, что имя есть на экране, и сам расскажу про один график.' : 'Открою новый файл и проверю с Тимуром, что его имя на экране.') : item.calm;
  story.calm.links.push(['calm-watch',quietLabel]);
  story['calm-watch'] = {...story[original],mode:'orange'};
  return addReactionScene(id,role,route);
}
