function addReactionScene(id, role, route) {
  const part = reactionScenes[id]?.[role];
  if (!part) return route;
  const {story,cues,decisions} = route;
  const self = role === 'self';
  const key = part.entry || 'meet-at-door';
  if (!part.entry) {
    const parent = self ? 'pressure' : 'check';
    const label = self ? 'Даня обещал ждать у раздевалки. Договорюсь с Мишей, где он меня встретит.' : 'Саша ждёт меня. Расскажу тренеру и подойду к двери вместе с ним.';
    story[parent].links.push([key,label]);
    story[key] = {parent,mode:self ? 'orange' : 'red',lines:[]};
    decisions[key] = {signals:decisions[self ? 'pressure-act-1' : 'call'].signals,effect:part.note};
  }
  const node = story[key];
  node.lines = [...node.lines,...part.lead,['Ремарка',part.pause],part.support];
  const pauseIndex = node.lines.length-2;
  if (self) {
    node.reaction = {index:pauseIndex,until:node.lines.length,summary:part.pause};
    node.lines.push(['Ремарка',part.ready]);
  }
  delete node.outcome;
  delete node.note;
  node.question = part.question;
  node.links = [];
  const cue = key+'-'+(pauseIndex+1);
  cues[cue] = [part.support[1],part.note];
  for (const [i,[mode,label,reply,headline]] of part.choices.entries()) {
    const target = key+'-next-'+i;
    node.links.push([target,label]);
    story[target] = {parent:key,mode,lines:[['Ремарка',reply]],outcome:['positive',headline],note:part.note};
    decisions[target] = {signals:[cue],effect:reply};
  }
  return route;
}
